// Regenerates the inline Lucide sprite in viewer/applogs-viewer.html, viewer/assets/icons/SOURCES.md
// and viewer/assets/icons/LICENSE-lucide.txt from an extracted lucide-static package:
//   node tests/viewer/gen-sprite.mjs <dir containing package.json, LICENSE and icons/>
// The package is not in the repo (CI has no network); static.test.mjs checks the committed result.
// To add an icon: add its name to ICONS (keep it sorted), rerun, commit the three files.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const HTML = path.join(ROOT, 'viewer', 'applogs-viewer.html');
export const ICON_DIR = path.join(ROOT, 'viewer', 'assets', 'icons');
export const VERSION = '1.49.0';
export const INTEGRITY = 'sha512-gSjtl7bR2v26oDInh2Wua1PrF2BRRXl9inhnLWcFfnRqRShmgZvlFRisPHqTfU7kxsuZU8ThNjAFotbInrzKow==';
export const TARBALL_SHA256 = 'c8c9d5dcbc50f388afea623ce2bcbef5788eb0b2d084081aa52d6adaae4ebba3';
export const ICONS = ['check', 'chevron-down', 'circle-alert', 'download', 'ellipsis', 'file-json', 'file-spreadsheet', 'file-text', 'folder-open', 'info', 'play', 'radio', 'search', 'square', 'triangle-alert', 'x'];
export const START = '<!-- lucide-sprite:start -->';
export const END = '<!-- lucide-sprite:end -->';
const SHAPES = /^<(path|circle|rect|line|polyline|polygon|ellipse)\b[^<>]*\/>$/;

const sha256 = buf => crypto.createHash('sha256').update(buf).digest('hex');

// The child elements of one icon file, on one line, as a <symbol>. Only plain shapes are accepted.
export function symbolFor(name, svgText) {
  const m = /<svg\b[^>]*>([\s\S]*?)<\/svg>/.exec(svgText);
  if (!m) throw new Error(`${name}: no <svg> root`);
  const shapes = m[1].split('\n').map(l => l.trim()).filter(Boolean);
  for (const s of shapes) {
    if (!SHAPES.test(s) || /\s(?:on\w+|style|href|xlink:href)=/i.test(s)) throw new Error(`${name}: unexpected content ${s}`);
  }
  return `<symbol id="i-${name}" viewBox="0 0 24 24">${shapes.join('')}</symbol>`;
}

export function build(pkgDir) {
  const pkg = JSON.parse(fs.readFileSync(path.join(pkgDir, 'package.json'), 'utf8'));
  if (pkg.name !== 'lucide-static' || pkg.version !== VERSION) throw new Error(`expected lucide-static@${VERSION}, got ${pkg.name}@${pkg.version}`);
  const files = ICONS.map(n => ({ name: n, bytes: fs.readFileSync(path.join(pkgDir, 'icons', `${n}.svg`)) }));
  const sprite = [START,
    '<svg id="iconSprite" class="icon-sprite" width="0" height="0" aria-hidden="true" focusable="false">',
    ...files.map(f => symbolFor(f.name, f.bytes.toString('utf8'))),
    '</svg>',
    END].join('\n');
  const sources = `# Bundled icons

Icon geometry from [Lucide](https://lucide.dev), package \`lucide-static\` ${VERSION} (ISC; the icons
derived from Feather are also MIT, see \`LICENSE-lucide.txt\`, the package's \`LICENSE\` verbatim).

Each icon is inlined as \`<symbol id="i-NAME" viewBox="0 0 24 24">\` in the sprite at the top of
\`<body>\` in \`viewer/applogs-viewer.html\` (pages opened from \`file://\` cannot \`<use>\` an external
SVG file in Chromium). Only the icon's child elements are copied. The root \`<svg>\` attributes and
the licence comment are dropped: stroke (\`currentColor\`, width 1.75 per the spec), caps and joins
come from the \`.icon\` rule in \`assets/css/base.css\`.

- Package: https://www.npmjs.com/package/lucide-static/v/${VERSION}
- Tarball: https://registry.npmjs.org/lucide-static/-/lucide-static-${VERSION}.tgz
- npm integrity: \`${INTEGRITY}\`
- Tarball SHA-256: \`${TARBALL_SHA256}\`

Generated by \`node tests/viewer/gen-sprite.mjs <extracted package>\`: to add an icon, add its name to
\`ICONS\` there and rerun. \`tests/viewer/static.test.mjs\` checks that this table and the sprite agree.

| Icon | Upstream file | SHA-256 of the upstream file |
|---|---|---|
${files.map(f => `| \`${f.name}\` | \`lucide-static@${VERSION}/icons/${f.name}.svg\` | \`${sha256(f.bytes)}\` |`).join('\n')}
`;
  return { sprite, sources, license: fs.readFileSync(path.join(pkgDir, 'LICENSE')) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const pkgDir = process.argv[2];
  if (!pkgDir) { console.error('usage: node tests/viewer/gen-sprite.mjs <extracted lucide-static package dir>'); process.exit(2); }
  const out = build(path.resolve(pkgDir));
  const html = fs.readFileSync(HTML, 'utf8');
  const a = html.indexOf(START);
  const b = html.indexOf(END);
  if (a < 0 || b < a || html.indexOf(START, a + 1) >= 0) throw new Error(`expected one ${START} … ${END} block in ${HTML}`);
  fs.writeFileSync(HTML, html.slice(0, a) + out.sprite + html.slice(b + END.length));
  fs.mkdirSync(ICON_DIR, { recursive: true });
  fs.writeFileSync(path.join(ICON_DIR, 'SOURCES.md'), out.sources);
  fs.writeFileSync(path.join(ICON_DIR, 'LICENSE-lucide.txt'), out.license);
  console.log(`wrote ${ICONS.length} symbols, icons/SOURCES.md and icons/LICENSE-lucide.txt`);
}
